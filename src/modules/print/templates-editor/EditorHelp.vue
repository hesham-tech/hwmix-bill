    else if (label.includes('X') || label.includes('Y')) text = 'المسافة بالملليمتر من أعلى يسار الملصق؛ X أفقي وY رأسي.';
    else if (label.includes('مم')) text = 'قيمة فعلية بالملليمتر، مستقلة عن تكبير المعاينة؛ راجع المساحة المتاحة.';
    else if (label.includes('دوران')) text = 'زاوية العنصر بالدرجات؛ رموز الباركود وQR تدور بمضاعفات 90 درجة.';
    else if (label.includes('X') || label.includes('Y')) text = 'المسافة بالملليمتر من أعلى يسار الملصق؛ X أفقي وY رأسي.';
    else if (label.includes('حقل') || target.classList.contains('v-list-item'))
      text = 'اختيار هذا الإجراء أو إضافة الحقل إلى النص المحدد؛ إن لم يُحدد نص يُضاف عنصر جديد.';
    else if (input) text = 'عدّل هذه القيمة للعنصر المحدد. العناصر المقفلة أو وضع المراجعة تمنع التعديل.';
    else text = 'استخدم هذا الإجراء في القالب الحالي؛ راجع اسم الإجراء وحالة الحفظ قبل المتابعة.';
  }
  const show = () => {
    if (menuOpen() || !target.isConnected) return;
    active = input || target;
    previousDescription = active.getAttribute('aria-describedby');
    active.setAttribute('aria-describedby', 'label-editor-help-tip');
    const r = target.getBoundingClientRect();
    position.value = { x: Math.max(8, Math.min(window.innerWidth - 328, r.left)), y: Math.max(8, Math.min(window.innerHeight - 110, r.bottom + 8)) };
    hint.value = text;
  };
  if (event.type === 'focusin') show();
  else timer = setTimeout(show, 450);
}
function escape(e) {
  if (e.key === 'Escape') hide();
}
function detach() {
  if (!attached) return;
  attached.removeEventListener('pointerover', inspect);
  attached.removeEventListener('pointerout', hide);
  attached.removeEventListener('focusin', inspect);
  attached.removeEventListener('focusout', hide);
  attached = null;
}
watch(
  () => props.root,
  root => {
    detach();
    if (root) {
      attached = document;
      attached.addEventListener('pointerover', inspect);
      attached.addEventListener('pointerout', hide);
      attached.addEventListener('focusin', inspect);
      attached.addEventListener('focusout', hide);
    }
  },
  { immediate: true }
);
defineExpose({
  show: () => {
    hide();
    open.value = true;
  },
});
window.addEventListener('resize', hide);
document.addEventListener('pointerdown', hide, true);
document.addEventListener('scroll', hide, true);
document.addEventListener('keydown', escape);
onBeforeUnmount(() => {
  hide();
  detach();
  document.removeEventListener('keydown', escape);
  window.removeEventListener('resize', hide);
  document.removeEventListener('scroll', hide, true);
  document.removeEventListener('pointerdown', hide, true);
  menuObserver.disconnect();
});
